-- DRAFT ONLY — review before generating a migration or applying to production.
-- Purpose: preserve distinct Terms and Privacy acceptance events at Auth signup.
-- Existing legacy 'terms_and_privacy' rows are intentionally retained unchanged.

begin;

-- Authenticated clients must not be able to forge arbitrary consent events.
-- The auth.users trigger runs as its trusted function owner and remains able to insert.
revoke insert on table public.krim_user_consent_events from authenticated;

create or replace function public.handle_new_customer()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
declare
  v_account_type text;
  v_terms_version text;
  v_privacy_version text;
begin
  -- Preserve the existing customer profile provisioning behaviour.
  insert into public.customer_profiles (
    id, full_name, company_name, phone
  )
  values (
    new.id,
    new.raw_user_meta_data->>'full_name',
    new.raw_user_meta_data->>'company_name',
    new.raw_user_meta_data->>'phone'
  );

  v_account_type := coalesce(
    new.raw_user_meta_data->>'krim_account_type',
    new.raw_user_meta_data->>'account_type',
    ''
  );

  if v_account_type in ('customer', 'partner')
     and coalesce(new.raw_user_meta_data->>'terms_accepted', 'false') = 'true'
  then
    v_terms_version := nullif(new.raw_user_meta_data->>'terms_version', '');
    v_privacy_version := nullif(new.raw_user_meta_data->>'privacy_version', '');

    if v_terms_version is null or v_privacy_version is null then
      raise exception 'Required Terms and Privacy policy versions are missing';
    end if;

    insert into public.krim_user_consent_events (
      user_id, consent_type, granted, policy_version
    )
    values
      (new.id, 'terms', true, v_terms_version),
      (new.id, 'privacy', true, v_privacy_version);
  end if;

  return new;
end;
$function$;

commit;

