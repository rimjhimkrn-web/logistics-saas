-- Leg-to-leg custody transfer with receiving-partner acceptance and dispatch gate.
CREATE TABLE public.krim_shipment_leg_custody_transfers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shipment_id bigint NOT NULL REFERENCES public.krim_shipments(id) ON DELETE CASCADE,
  from_leg_id bigint NOT NULL,
  to_leg_id bigint NOT NULL,
  releasing_organization_id bigint NOT NULL REFERENCES public.krim_organizations(id),
  receiving_organization_id bigint NOT NULL REFERENCES public.krim_organizations(id),
  status text NOT NULL DEFAULT 'pending',
  cargo_manifest jsonb NOT NULL,
  cargo_condition text NOT NULL,
  seal_number text,
  discrepancy_note text,
  evidence_bucket_id text NOT NULL,
  evidence_storage_path text NOT NULL,
  idempotency_key text NOT NULL,
  created_by uuid NOT NULL REFERENCES auth.users(id),
  accepted_by uuid REFERENCES auth.users(id),
  accepted_at timestamptz,
  response_reason text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT fk_krim_custody_from_leg FOREIGN KEY(from_leg_id,shipment_id)
    REFERENCES public.krim_shipment_legs(id,shipment_id) ON DELETE RESTRICT,
  CONSTRAINT fk_krim_custody_to_leg FOREIGN KEY(to_leg_id,shipment_id)
    REFERENCES public.krim_shipment_legs(id,shipment_id) ON DELETE RESTRICT,
  CONSTRAINT chk_krim_custody_distinct_legs CHECK(from_leg_id<>to_leg_id),
  CONSTRAINT chk_krim_custody_status CHECK(status IN ('pending','accepted','rejected','cancelled')),
  CONSTRAINT chk_krim_custody_condition CHECK(cargo_condition IN ('good','damaged','short','overage','unknown')),
  CONSTRAINT chk_krim_custody_manifest_array CHECK(jsonb_typeof(cargo_manifest)='array' AND jsonb_array_length(cargo_manifest)>0),
  CONSTRAINT uq_krim_custody_idempotency UNIQUE(releasing_organization_id,idempotency_key)
);

CREATE INDEX idx_krim_custody_transfer_to_leg_status
  ON public.krim_shipment_leg_custody_transfers(to_leg_id,status);
CREATE INDEX idx_krim_custody_transfer_shipment
  ON public.krim_shipment_leg_custody_transfers(shipment_id,created_at DESC);

CREATE TABLE public.krim_shipment_leg_custody_transfer_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transfer_id bigint NOT NULL REFERENCES public.krim_shipment_leg_custody_transfers(id) ON DELETE RESTRICT,
  event_type text NOT NULL,
  actor_user_id uuid REFERENCES auth.users(id),
  event_time timestamptz NOT NULL DEFAULT now(),
  payload jsonb NOT NULL DEFAULT '{}'::jsonb
);

ALTER TABLE public.krim_shipment_leg_custody_transfers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.krim_shipment_leg_custody_transfer_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.krim_shipment_leg_custody_transfers FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON public.krim_shipment_leg_custody_transfer_events FROM PUBLIC, anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION public.krim_create_leg_custody_transfer(
  p_from_leg_id bigint,
  p_to_leg_id bigint,
  p_cargo_manifest jsonb,
  p_cargo_condition text,
  p_seal_number text,
  p_discrepancy_note text,
  p_evidence_storage_path text,
  p_idempotency_key text
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_user uuid := auth.uid();
  v_from public.krim_shipment_legs%rowtype;
  v_to public.krim_shipment_legs%rowtype;
  v_transfer public.krim_shipment_leg_custody_transfers%rowtype;
  v_expected_count integer;
BEGIN
  IF v_user IS NULL THEN RAISE EXCEPTION 'Authentication required' USING errcode='28000'; END IF;
  IF p_from_leg_id IS NULL OR p_to_leg_id IS NULL OR p_cargo_manifest IS NULL
     OR jsonb_typeof(p_cargo_manifest)<>'array' OR jsonb_array_length(p_cargo_manifest)=0
     OR p_cargo_condition NOT IN ('good','damaged','short','overage','unknown')
     OR nullif(btrim(p_evidence_storage_path),'') IS NULL
     OR nullif(btrim(p_idempotency_key),'') IS NULL OR length(p_idempotency_key)>160 THEN
    RAISE EXCEPTION 'Valid adjacent legs, cargo manifest, condition, private evidence path and idempotency key are required'
      USING errcode='22023';
  END IF;

  SELECT * INTO v_from FROM public.krim_shipment_legs WHERE id=p_from_leg_id FOR UPDATE;
  SELECT * INTO v_to FROM public.krim_shipment_legs WHERE id=p_to_leg_id FOR UPDATE;
  IF v_from.id IS NULL OR v_to.id IS NULL OR v_from.shipment_id<>v_to.shipment_id
     OR v_to.leg_sequence<>v_from.leg_sequence+1
     OR v_from.leg_plan_item_id IS NULL OR v_to.leg_plan_item_id IS NULL
     OR v_from.partner_organization_id IS NULL OR v_to.partner_organization_id IS NULL
     OR v_from.partner_organization_id=v_to.partner_organization_id THEN
    RAISE EXCEPTION 'Custody transfer requires adjacent legs in the same active multi-partner route plan'
      USING errcode='23514';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.krim_shipment_leg_plan_items fi
    JOIN public.krim_shipment_leg_plans fp ON fp.id=fi.plan_id
    JOIN public.krim_shipment_leg_plan_items ti ON ti.plan_id=fi.plan_id
    JOIN public.krim_shipment_leg_plans tp ON tp.id=ti.plan_id
    WHERE fi.id=v_from.leg_plan_item_id AND ti.id=v_to.leg_plan_item_id
      AND fi.leg_sequence=v_from.leg_sequence AND ti.leg_sequence=v_to.leg_sequence
      AND fp.shipment_id=v_from.shipment_id AND tp.shipment_id=v_from.shipment_id
      AND fp.status='active' AND tp.status='active'
  ) THEN
    RAISE EXCEPTION 'Both legs must belong to the same active route plan' USING errcode='23514';
  END IF;
  IF v_from.status NOT IN ('completed','delivered') OR v_from.actual_arrival IS NULL THEN
    RAISE EXCEPTION 'The releasing leg must be completed with a recorded actual arrival before custody transfer'
      USING errcode='23514';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.krim_shipment_partner_assignments a
    WHERE a.shipment_id=v_from.shipment_id AND a.shipment_leg_id=v_from.id
      AND a.partner_organization_id=v_from.partner_organization_id
      AND a.status IN ('active','completed')
  ) THEN
    RAISE EXCEPTION 'Completed releasing-partner assignment is required' USING errcode='23514';
  END IF;
  IF NOT private.krim_has_permission(v_user,v_from.partner_organization_id,'partner.manage') THEN
    RAISE EXCEPTION 'Active releasing-partner membership and partner.manage permission required' USING errcode='42501';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.krim_shipment_partner_assignments a
    WHERE a.shipment_id=v_to.shipment_id AND a.shipment_leg_id=v_to.id
      AND a.partner_organization_id=v_to.partner_organization_id
      AND a.status IN ('accepted','active')
  ) THEN
    RAISE EXCEPTION 'Receiving partner must have an accepted assignment for the next leg' USING errcode='23514';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.krim_capacity_leg_bindings b
    JOIN public.krim_capacity_reservations r ON r.id=b.reservation_id
    WHERE b.shipment_id=v_to.shipment_id AND b.shipment_leg_id=v_to.id
      AND b.status='confirmed' AND r.status='confirmed'
      AND r.organization_id=v_to.partner_organization_id
  ) THEN
    RAISE EXCEPTION 'Confirmed physical capacity reservation for the receiving leg is required' USING errcode='23514';
  END IF;

  SELECT count(*)::integer INTO v_expected_count
  FROM public.krim_shipment_cargo c WHERE c.shipment_id=v_from.shipment_id;
  IF v_expected_count=0 OR jsonb_array_length(p_cargo_manifest)<>v_expected_count
     OR EXISTS (
       SELECT 1 FROM public.krim_shipment_cargo c
       WHERE c.shipment_id=v_from.shipment_id
       AND NOT EXISTS (
         SELECT 1 FROM jsonb_array_elements(p_cargo_manifest) m
         WHERE (m->>'cargo_id') ~ '^[0-9]+$'
           AND (m->>'cargo_id')::bigint=c.id
           AND pg_catalog.pg_input_is_valid(m->>'quantity','numeric')
           AND (m->>'quantity')::numeric=c.quantity
           AND lower(coalesce(m->>'unit',''))=lower(coalesce(c.quantity_unit,''))
       )
     ) THEN
    RAISE EXCEPTION 'Custody manifest must account for every shipment cargo line with its exact recorded quantity and unit'
      USING errcode='23514';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM storage.objects o
    WHERE o.bucket_id='krim-warehouse-evidence'
      AND o.name=btrim(p_evidence_storage_path)
      AND o.owner=v_user
      AND split_part(o.name,'/',1)=v_from.partner_organization_id::text
      AND split_part(o.name,'/',2)=v_user::text
      AND cardinality(string_to_array(o.name,'/'))=3
      AND coalesce(o.metadata->>'mimetype','') IN ('image/jpeg','image/png','application/pdf')
      AND pg_catalog.pg_input_is_valid(o.metadata->>'size','bigint')
      AND (o.metadata->>'size')::bigint BETWEEN 1 AND 10485760
  ) THEN
    RAISE EXCEPTION 'Upload private uploader-owned custody evidence to the KRIM warehouse evidence bucket using the releasing organisation/user path'
      USING errcode='23514';
  END IF;

  PERFORM pg_advisory_xact_lock(hashtextextended('krim_custody:'||v_from.partner_organization_id::text||':'||p_idempotency_key,0));
  SELECT * INTO v_transfer FROM public.krim_shipment_leg_custody_transfers
  WHERE releasing_organization_id=v_from.partner_organization_id AND idempotency_key=p_idempotency_key;
  IF FOUND THEN
    IF v_transfer.shipment_id<>v_from.shipment_id OR v_transfer.from_leg_id<>v_from.id
       OR v_transfer.to_leg_id<>v_to.id OR v_transfer.cargo_manifest<>p_cargo_manifest
       OR v_transfer.cargo_condition<>p_cargo_condition
       OR v_transfer.evidence_storage_path<>btrim(p_evidence_storage_path) THEN
      RAISE EXCEPTION 'Idempotency key was already used for a different custody transfer' USING errcode='23505';
    END IF;
    RETURN jsonb_build_object('replayed',true,'transfer',to_jsonb(v_transfer));
  END IF;

  INSERT INTO public.krim_shipment_leg_custody_transfers(
    shipment_id,from_leg_id,to_leg_id,releasing_organization_id,receiving_organization_id,
    cargo_manifest,cargo_condition,seal_number,discrepancy_note,evidence_bucket_id,
    evidence_storage_path,idempotency_key,created_by
  ) VALUES (
    v_from.shipment_id,v_from.id,v_to.id,v_from.partner_organization_id,v_to.partner_organization_id,
    p_cargo_manifest,p_cargo_condition,nullif(btrim(p_seal_number),''),left(coalesce(p_discrepancy_note,''),2000),
    'krim-warehouse-evidence',btrim(p_evidence_storage_path),p_idempotency_key,v_user
  ) RETURNING * INTO v_transfer;

  INSERT INTO public.krim_shipment_leg_custody_transfer_events(transfer_id,event_type,actor_user_id,payload)
  VALUES(v_transfer.id,'custody_transfer.offered',v_user,
    jsonb_build_object('shipment_id',v_from.shipment_id,'from_leg_id',v_from.id,'to_leg_id',v_to.id,
      'releasing_organization_id',v_from.partner_organization_id,'receiving_organization_id',v_to.partner_organization_id,
      'cargo_condition',p_cargo_condition,'evidence_bucket_id','krim-warehouse-evidence'));

  RETURN jsonb_build_object('replayed',false,'transfer',to_jsonb(v_transfer));
END;
$function$;

CREATE OR REPLACE FUNCTION public.krim_respond_to_leg_custody_transfer(
  p_transfer_id bigint,
  p_accept boolean,
  p_reason text
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_user uuid:=auth.uid();
  v_transfer public.krim_shipment_leg_custody_transfers%rowtype;
  v_to public.krim_shipment_legs%rowtype;
BEGIN
  IF v_user IS NULL THEN RAISE EXCEPTION 'Authentication required' USING errcode='28000'; END IF;
  IF p_transfer_id IS NULL OR p_accept IS NULL OR (NOT p_accept AND nullif(btrim(p_reason),'') IS NULL) THEN
    RAISE EXCEPTION 'Transfer, response and rejection reason when rejecting are required' USING errcode='22023';
  END IF;
  SELECT * INTO v_transfer FROM public.krim_shipment_leg_custody_transfers
  WHERE id=p_transfer_id FOR UPDATE;
  IF v_transfer.id IS NULL THEN RAISE EXCEPTION 'Custody transfer not found' USING errcode='P0002'; END IF;
  IF NOT private.krim_has_permission(v_user,v_transfer.receiving_organization_id,'partner.manage') THEN
    RAISE EXCEPTION 'Active receiving-partner membership and partner.manage permission required' USING errcode='42501';
  END IF;
  IF v_transfer.status='accepted' AND p_accept THEN
    RETURN jsonb_build_object('replayed',true,'transfer',to_jsonb(v_transfer));
  ELSIF v_transfer.status='rejected' AND NOT p_accept THEN
    RETURN jsonb_build_object('replayed',true,'transfer',to_jsonb(v_transfer));
  ELSIF v_transfer.status<>'pending' THEN
    RAISE EXCEPTION 'Custody transfer is no longer awaiting a response' USING errcode='23514';
  END IF;

  SELECT * INTO v_to FROM public.krim_shipment_legs WHERE id=v_transfer.to_leg_id FOR UPDATE;
  IF v_to.shipment_id<>v_transfer.shipment_id OR v_to.partner_organization_id<>v_transfer.receiving_organization_id THEN
    RAISE EXCEPTION 'Receiving leg or partner binding has changed' USING errcode='23514';
  END IF;
  IF p_accept THEN
    IF NOT EXISTS (
      SELECT 1 FROM public.krim_shipment_partner_assignments a
      WHERE a.shipment_id=v_to.shipment_id AND a.shipment_leg_id=v_to.id
        AND a.partner_organization_id=v_to.partner_organization_id
        AND a.status IN ('accepted','active')
    ) OR NOT EXISTS (
      SELECT 1 FROM public.krim_capacity_leg_bindings b
      JOIN public.krim_capacity_reservations r ON r.id=b.reservation_id
      WHERE b.shipment_id=v_to.shipment_id AND b.shipment_leg_id=v_to.id
        AND b.status='confirmed' AND r.status='confirmed'
        AND r.organization_id=v_to.partner_organization_id
    ) THEN
      RAISE EXCEPTION 'Receiving assignment and confirmed physical capacity must remain valid at acceptance' USING errcode='23514';
    END IF;
    UPDATE public.krim_shipment_leg_custody_transfers
      SET status='accepted',accepted_by=v_user,accepted_at=now(),response_reason=null,updated_at=now()
      WHERE id=v_transfer.id RETURNING * INTO v_transfer;
  ELSE
    UPDATE public.krim_shipment_leg_custody_transfers
      SET status='rejected',accepted_by=v_user,accepted_at=now(),response_reason=left(btrim(p_reason),2000),updated_at=now()
      WHERE id=v_transfer.id RETURNING * INTO v_transfer;
  END IF;
  INSERT INTO public.krim_shipment_leg_custody_transfer_events(transfer_id,event_type,actor_user_id,payload)
  VALUES(v_transfer.id,CASE WHEN p_accept THEN 'custody_transfer.accepted' ELSE 'custody_transfer.rejected' END,
    v_user,jsonb_build_object('receiving_organization_id',v_transfer.receiving_organization_id,'reason',v_transfer.response_reason));
  RETURN jsonb_build_object('replayed',false,'transfer',to_jsonb(v_transfer));
END;
$function$;

CREATE OR REPLACE FUNCTION private.krim_require_accepted_custody_before_next_leg_dispatch()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
BEGIN
  IF NEW.status='in_transit' AND OLD.status IS DISTINCT FROM NEW.status
     AND NEW.leg_sequence>1
     AND NEW.leg_plan_item_id IS NOT NULL
     AND EXISTS (
       SELECT 1 FROM public.krim_shipment_leg_plans p
       WHERE p.shipment_id=NEW.shipment_id AND p.status='active' AND p.total_legs>1
     )
     AND NOT EXISTS (
       SELECT 1 FROM public.krim_shipment_legs prior_leg
       JOIN public.krim_shipment_leg_custody_transfers t
         ON t.from_leg_id=prior_leg.id AND t.to_leg_id=NEW.id
       WHERE prior_leg.shipment_id=NEW.shipment_id
         AND prior_leg.leg_sequence=NEW.leg_sequence-1
         AND t.status='accepted'
         AND t.releasing_organization_id=prior_leg.partner_organization_id
         AND t.receiving_organization_id=NEW.partner_organization_id
     ) THEN
    RAISE EXCEPTION USING errcode='23514',
      message='Next route leg cannot enter transit until the immediately preceding leg custody transfer is accepted by the receiving partner';
  END IF;
  RETURN NEW;
END;
$function$;

REVOKE ALL ON FUNCTION private.krim_require_accepted_custody_before_next_leg_dispatch()
FROM PUBLIC, anon, authenticated, service_role;
DROP TRIGGER IF EXISTS trg_krim_require_accepted_custody_before_next_leg_dispatch ON public.krim_shipment_legs;
CREATE TRIGGER trg_krim_require_accepted_custody_before_next_leg_dispatch
BEFORE UPDATE OF status ON public.krim_shipment_legs
FOR EACH ROW EXECUTE FUNCTION private.krim_require_accepted_custody_before_next_leg_dispatch();

