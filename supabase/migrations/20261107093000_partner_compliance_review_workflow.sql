create table if not exists public.krim_partner_compliance_reviews (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references public.krim_organizations(id) on delete restrict,
  verification_case_id bigint references public.krim_partner_verification_cases(id) on delete restrict,
  jurisdiction_code text not null check (jurisdiction_code ~ '^[A-Z]{2}$'),
  status text not null default 'in_review' check (status in ('in_review','approved','rejected','on_hold','expired')),
  checks jsonb not null default '[]'::jsonb check (jsonb_typeof(checks)='array'),
  reviewer_note text not null,
  valid_until timestamptz,
  reviewed_by uuid not null,
  reviewed_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (valid_until is null or valid_until > reviewed_at)
);
create index if not exists krim_partner_compliance_reviews_org_idx on public.krim_partner_compliance_reviews(organization_id,reviewed_at desc);
create index if not exists krim_partner_compliance_reviews_status_idx on public.krim_partner_compliance_reviews(status,reviewed_at desc);
alter table public.krim_partner_compliance_reviews enable row level security;
alter table public.krim_partner_compliance_reviews force row level security;
revoke all on public.krim_partner_compliance_reviews from public,anon,authenticated;
revoke all on sequence public.krim_partner_compliance_reviews_id_seq from public,anon,authenticated;

create or replace function public.krim_admin_list_partner_compliance_reviews()
returns jsonb language plpgsql security definer set search_path='' as $$
declare u uuid:=auth.uid(); result jsonb;
begin
 if u is null or coalesce(auth.jwt()->>'aal','')<>'aal2'
    or not private.krim_has_permission(u,1::bigint,'admin.platform') then
   raise exception using errcode='42501',message='AAL2 platform administrator access required';
 end if;
 select coalesce(jsonb_agg(jsonb_build_object(
   'organization_id',o.id,'legal_name',o.legal_name,'organization_type',o.organization_type,
   'organization_status',o.status,'account_mode',o.partner_account_mode,
   'verification_status',o.partner_verification_status,'compliance_status',o.partner_compliance_status,
   'lifecycle_status',o.partner_lifecycle_status,'onboarding_status',o.partner_onboarding_status,
   'country_code',coalesce(c.iso2_code,upper(c.code)),
   'country_name',c.name,
   'verification_case_id',vc.id,'verification_case_number',vc.case_number,
   'document_paths',coalesce(o.partner_metadata->'document_paths','[]'::jsonb),
   'latest_review',(
     select to_jsonb(r) - 'reviewed_by' from public.krim_partner_compliance_reviews r
     where r.organization_id=o.id order by r.reviewed_at desc limit 1
   )
 ) order by o.legal_name),'[]'::jsonb)
 into result
 from public.krim_organizations o
 left join public.krim_countries c on c.id=o.country_id
 left join lateral (
   select x.id,x.case_number from public.krim_partner_verification_cases x
   where x.organization_id=o.id and x.status='approved'
   order by x.completed_at desc nulls last,x.id desc limit 1
 ) vc on true
 where o.partner_account_mode='registered_business'
   and o.partner_verification_status='verified'
   and o.partner_lifecycle_status in ('approved','active','restricted')
   and o.organization_type in ('partner','carrier','warehouse','forwarder','logistics_provider','warehouse_operator');
 return jsonb_build_object('reviews',result);
end $$;

create or replace function public.krim_admin_review_partner_compliance(
 p_organization_id bigint,
 p_decision text,
 p_checks jsonb,
 p_reviewer_note text,
 p_valid_until timestamptz default null
) returns jsonb language plpgsql security definer set search_path='' as $$
declare
 u uuid:=auth.uid();
 o public.krim_organizations%rowtype;
 v_case_id bigint;
 v_country_code text;
 v_decision text:=lower(nullif(btrim(p_decision),''));
 v_note text:=nullif(btrim(coalesce(p_reviewer_note,'')),'');
 v_required text[]:=array['business_registration','tax_registration','operating_authority','insurance_liability'];
 v_item jsonb;
 v_code text;
 v_status text;
 v_path text;
 v_reason text;
 v_seen text[]:=array[]::text[];
 v_old jsonb;
 v_new jsonb;
 v_id bigint;
begin
 if u is null or coalesce(auth.jwt()->>'aal','')<>'aal2'
    or not private.krim_has_permission(u,1::bigint,'admin.platform') then
   raise exception using errcode='42501',message='AAL2 platform administrator access required';
 end if;
 if p_organization_id is null or v_decision is null or v_decision not in ('approved','rejected','on_hold') then
   raise exception using errcode='22023',message='Choose a partner and a valid compliance decision';
 end if;
 if v_note is null or char_length(v_note)<20 or char_length(v_note)>2000 then
   raise exception using errcode='22023',message='A reviewer rationale of 20 to 2000 characters is required';
 end if;
 if jsonb_typeof(p_checks) is distinct from 'array' or jsonb_array_length(p_checks)<>4 then
   raise exception using errcode='22023',message='Exactly four baseline compliance checks are required';
 end if;
 if p_valid_until is not null and (p_valid_until<=now() or p_valid_until>now()+interval '365 days') then
   raise exception using errcode='22023',message='Review validity must be within the next 365 days';
 end if;
 select * into o from public.krim_organizations where id=p_organization_id for update;
 if not found then raise exception using errcode='P0002',message='Partner organization not found'; end if;
 if o.partner_account_mode<>'registered_business'
    or o.partner_verification_status<>'verified'
    or o.partner_lifecycle_status not in ('approved','active')
    or o.status<>'active'
    or o.organization_type not in ('partner','carrier','warehouse','forwarder','logistics_provider','warehouse_operator') then
   raise exception using errcode='23514',message='Only an active, registered-business organisation with verified business identity can enter compliance review';
 end if;
 select coalesce(c.iso2_code,upper(c.code)) into v_country_code
 from public.krim_countries c where c.id=o.country_id;
 if v_country_code is null or v_country_code !~ '^[A-Z]{2}$' then
   raise exception using errcode='23514',message='A valid country jurisdiction is required before compliance review';
 end if;
 select id into v_case_id from public.krim_partner_verification_cases
 where organization_id=o.id and status='approved'
 order by completed_at desc nulls last,id desc limit 1;
 foreach v_code in array v_required loop
   if not exists (select 1 from jsonb_array_elements(p_checks) x where x->>'code'=v_code) then
     raise exception using errcode='22023',message='Missing baseline compliance check: '||v_code;
   end if;
 end loop;
 for v_item in select value from jsonb_array_elements(p_checks) loop
   v_code:=v_item->>'code'; v_status:=v_item->>'status';
   v_path:=nullif(btrim(v_item->>'evidence_path'),'');
   v_reason:=nullif(btrim(v_item->>'rationale'),'');
   if v_code is null or not (v_code=any(v_required)) or v_code=any(v_seen) then
     raise exception using errcode='22023',message='Unknown or duplicate compliance check code';
   end if;
   v_seen:=array_append(v_seen,v_code);
   if v_status is null or v_status not in ('verified','not_applicable','pending','rejected') then
     raise exception using errcode='22023',message='Invalid compliance check status';
   end if;
   if v_status='verified' then
     if v_path is null or v_path !~ ('^'||o.id::text||'/[0-9a-fA-F-]{36}/[^/]+\.(pdf|png|jpe?g)$') then
       raise exception using errcode='23514',message='Verified check requires a correctly scoped evidence file in private partner storage';
     end if;
     if not exists(select 1 from storage.objects so where so.bucket_id='krim-partner-verification' and so.name=v_path) then
       raise exception using errcode='23514',message='A referenced compliance evidence file is missing from private storage';
     end if;
   elsif v_status='not_applicable' then
     if v_reason is null or char_length(v_reason)<10 then
       raise exception using errcode='22023',message='Not-applicable decisions require a rationale of at least 10 characters';
     end if;
   end if;
 end loop;
 if v_decision='approved' and exists (
   select 1 from jsonb_array_elements(p_checks) x
   where x->>'status' not in ('verified','not_applicable')
 ) then
   raise exception using errcode='23514',message='Compliance cannot be cleared while any baseline check is pending or rejected';
 end if;
 if v_decision='approved' and exists (
   select 1 from jsonb_array_elements(p_checks) x
   where x->>'status'='not_applicable' and length(coalesce(x->>'rationale',''))<10
 ) then
   raise exception using errcode='23514',message='Every not-applicable item needs a reason';
 end if;
 v_old:=jsonb_build_object('compliance_status',o.partner_compliance_status,'lifecycle_status',o.partner_lifecycle_status);
 insert into public.krim_partner_compliance_reviews
  (organization_id,verification_case_id,jurisdiction_code,status,checks,reviewer_note,valid_until,reviewed_by)
 values
  (o.id,v_case_id,v_country_code,
   case when v_decision='approved' then 'approved' when v_decision='rejected' then 'rejected' else 'on_hold' end,
   p_checks,v_note,p_valid_until,u)
 returning id into v_id;
 if v_decision='approved' then
   update public.krim_organizations
   set partner_compliance_status='compliant',partner_lifecycle_status='approved',
       partner_reviewed_at=now(),partner_reviewed_by=u,
       partner_review_notes=v_note,updated_at=now()
   where id=o.id;
 elsif v_decision='rejected' then
   update public.krim_organizations
   set partner_compliance_status='non_compliant',partner_lifecycle_status='restricted',
       partner_restricted_at=now(),partner_reviewed_at=now(),partner_reviewed_by=u,
       partner_review_notes=v_note,updated_at=now()
   where id=o.id;
 else
   update public.krim_organizations
   set partner_compliance_status='pending',partner_lifecycle_status='approved',
       partner_reviewed_at=now(),partner_reviewed_by=u,
       partner_review_notes=v_note,updated_at=now()
   where id=o.id;
 end if;
 v_new:=jsonb_build_object('compliance_status',case when v_decision='approved' then 'compliant' when v_decision='rejected' then 'non_compliant' else 'pending' end,
   'lifecycle_status',case when v_decision='rejected' then 'restricted' else 'approved' end,
   'review_id',v_id,'decision',v_decision);
 insert into public.krim_audit_events(actor_user_id,organization_id,event_type,entity_type,entity_id,source,metadata,previous_state,new_state)
 values(u,o.id,'partner.compliance.reviewed','partner_compliance_review',v_id::text,'partner_compliance',
   jsonb_build_object('decision',v_decision,'jurisdiction_code',v_country_code,'reviewer_note',v_note),v_old,v_new);
 return jsonb_build_object('success',true,'review_id',v_id,'organization_id',o.id,'decision',v_decision,'compliance_status',v_new->>'compliance_status','commercial_activation',false);
end $$;

revoke all on function public.krim_admin_list_partner_compliance_reviews() from public,anon;
