create table if not exists public.krim_customs_broker_assignments (
  id bigint generated by default as identity primary key,
  customs_record_id bigint not null references public.krim_shipment_customs(id) on delete restrict,
  shipment_id bigint not null references public.krim_shipments(id) on delete restrict,
  broker_organization_id bigint not null references public.krim_organizations(id) on delete restrict,
  jurisdiction_country_id bigint references public.krim_countries(id) on delete restrict,
  assignment_status text not null default 'proposed'
    check (assignment_status in ('proposed','accepted','rejected','revoked','completed')),
  assignment_note text not null default '',
  assigned_by uuid,
  assigned_at timestamptz not null default now(),
  accepted_by uuid,
  accepted_at timestamptz,
  rejected_by uuid,
  rejected_at timestamptz,
  revoked_by uuid,
  revoked_at timestamptz,
  completed_by uuid,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint krim_customs_broker_assignment_shipment_record_unique unique (id, shipment_id, customs_record_id)
);
create index if not exists krim_customs_broker_assignments_record_status_idx
  on public.krim_customs_broker_assignments (customs_record_id, assignment_status, assigned_at desc);
create index if not exists krim_customs_broker_assignments_broker_status_idx
  on public.krim_customs_broker_assignments (broker_organization_id, assignment_status, assigned_at desc);
create index if not exists krim_customs_broker_assignments_shipment_idx
  on public.krim_customs_broker_assignments (shipment_id, assigned_at desc);
alter table public.krim_customs_broker_assignments enable row level security;
alter table public.krim_customs_broker_assignments force row level security;
revoke all on table public.krim_customs_broker_assignments from public, anon, authenticated;
revoke all on sequence public.krim_customs_broker_assignments_id_seq from public, anon, authenticated;
comment on table public.krim_customs_broker_assignments is 'Customs broker assignments scoped to a customs record and shipment. Direct client access is intentionally disabled until guarded assignment and acceptance RPCs are deployed.';