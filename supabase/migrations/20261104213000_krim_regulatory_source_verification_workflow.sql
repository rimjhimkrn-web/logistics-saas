create table if not exists public.krim_market_regulatory_sources (
 id bigint generated by default as identity primary key,
 requirement_id bigint not null references public.krim_market_readiness_requirements(id) on delete restrict,
 jurisdiction_code text not null,
 source_kind text not null check (source_kind in ('official_primary','official_secondary','qualified_legal_opinion','qualified_tax_opinion','licensed_provider_evidence','other')),
 title text not null,
 issuer text not null,
 source_url text,
 version_label text,
 published_at date,
 effective_from date,
 effective_until date,
 retrieved_at timestamptz not null default now(),
 sha256 text,
 evidence_reference text,
 reviewer_notes text,
 review_status text not null default 'pending' check (review_status in ('pending','source_checked','legal_review_pending','legal_reviewed','rejected','retired')),
 reviewed_by uuid,
 reviewed_at timestamptz,
 created_by uuid not null,
 created_at timestamptz not null default now(),
 constraint krim_market_source_https_chk check (source_url is null or source_url ~ '^https://'),
 constraint krim_market_source_sha_chk check (sha256 is null or sha256 ~ '^[A-Fa-f0-9]{64}$'),
 constraint krim_market_source_effective_chk check (effective_until is null or effective_from is null or effective_until >= effective_from)
);
create table if not exists public.krim_market_regulatory_source_events (
 id bigint generated by default as identity primary key,
 source_id bigint not null references public.krim_market_regulatory_sources(id) on delete restrict,
 actor_user_id uuid not null,
 previous_status text,
 new_status text not null,
 rationale text not null,
 evidence_reference text,
 created_at timestamptz not null default now()
);
create index if not exists krim_market_sources_requirement_idx on public.krim_market_regulatory_sources(requirement_id,review_status);
create index if not exists krim_market_sources_jurisdiction_idx on public.krim_market_regulatory_sources(jurisdiction_code,review_status);
alter table public.krim_market_regulatory_sources enable row level security;
alter table public.krim_market_regulatory_sources force row level security;
alter table public.krim_market_regulatory_source_events enable row level security;
alter table public.krim_market_regulatory_source_events force row level security;
revoke all on public.krim_market_regulatory_sources from anon,authenticated;
revoke all on public.krim_market_regulatory_source_events from anon,authenticated;
revoke all on sequence public.krim_market_regulatory_sources_id_seq from anon,authenticated;
revoke all on sequence public.krim_market_regulatory_source_events_id_seq from anon,authenticated;

create or replace function public.krim_admin_list_regulatory_sources(p_requirement_id bigint default null)
returns jsonb language plpgsql security definer set search_path=''
as $$
declare v_user uuid:=auth.uid(); v_result jsonb;
begin
 if v_user is null then raise exception using errcode='28000',message='Authentication required'; end if;
 if coalesce(auth.jwt()->>'aal','aal1')<>'aal2' then raise exception using errcode='42501',message='AAL2 required'; end if;
 if not private.krim_has_permission(v_user,1::bigint,'admin.platform') then raise exception using errcode='42501',message='Platform administrator permission required'; end if;
 select coalesce(jsonb_agg(jsonb_build_object(
  'id',s.id,'requirement_id',s.requirement_id,'requirement_code',r.requirement_code,
  'jurisdiction_code',s.jurisdiction_code,'source_kind',s.source_kind,'title',s.title,'issuer',s.issuer,
  'source_url',s.source_url,'version_label',s.version_label,'published_at',s.published_at,
  'effective_from',s.effective_from,'effective_until',s.effective_until,'retrieved_at',s.retrieved_at,
  'sha256',s.sha256,'evidence_reference',s.evidence_reference,'reviewer_notes',s.reviewer_notes,
  'review_status',s.review_status,'reviewed_at',s.reviewed_at,'created_at',s.created_at
 ) order by s.created_at desc),'[]'::jsonb) into v_result
 from public.krim_market_regulatory_sources s
 join public.krim_market_readiness_requirements r on r.id=s.requirement_id
 where p_requirement_id is null or s.requirement_id=p_requirement_id;
 return jsonb_build_object('sources',v_result,'generated_at',now());
end; $$;

create or replace function public.krim_admin_register_regulatory_source(
 p_requirement_id bigint,p_jurisdiction_code text,p_source_kind text,p_title text,p_issuer text,
 p_source_url text default null,p_version_label text default null,p_published_at date default null,
 p_effective_from date default null,p_effective_until date default null,p_sha256 text default null,
 p_evidence_reference text default null,p_reviewer_notes text default null
) returns jsonb language plpgsql security definer set search_path=''
as $$
declare v_user uuid:=auth.uid(); v_req public.krim_market_readiness_requirements%rowtype; v_id bigint;
begin
 if v_user is null then raise exception using errcode='28000',message='Authentication required'; end if;
 if coalesce(auth.jwt()->>'aal','aal1')<>'aal2' then raise exception using errcode='42501',message='AAL2 required'; end if;
 if not private.krim_has_permission(v_user,1::bigint,'admin.platform') then raise exception using errcode='42501',message='Platform administrator permission required'; end if;
 select * into v_req from public.krim_market_readiness_requirements where id=p_requirement_id and source_review_status<>'retired';
 if not found then raise exception using errcode='P0002',message='Active requirement not found'; end if;
 if p_jurisdiction_code not in ('*',v_req.jurisdiction_code) and v_req.jurisdiction_code<>'*' then
  raise exception using errcode='22023',message='Source jurisdiction does not match requirement'; end if;
 if p_source_kind not in ('official_primary','official_secondary','qualified_legal_opinion','qualified_tax_opinion','licensed_provider_evidence','other')
  or length(btrim(coalesce(p_title,'')))<4 or length(btrim(coalesce(p_issuer,'')))<2 then
  raise exception using errcode='22023',message='Source type, title and issuer are required'; end if;
 if p_source_kind in ('official_primary','official_secondary') and (p_source_url is null or p_source_url !~ '^https://') then
  raise exception using errcode='22023',message='Official source must have an HTTPS URL'; end if;
 if p_source_kind in ('qualified_legal_opinion','qualified_tax_opinion','licensed_provider_evidence') and nullif(btrim(p_evidence_reference),'') is null then
  raise exception using errcode='22023',message='Professional opinion or licence evidence reference is required'; end if;
 if p_sha256 is not null and p_sha256 !~ '^[A-Fa-f0-9]{64}$' then raise exception using errcode='22023',message='SHA-256 must contain 64 hexadecimal characters'; end if;
 insert into public.krim_market_regulatory_sources(requirement_id,jurisdiction_code,source_kind,title,issuer,source_url,version_label,published_at,effective_from,effective_until,sha256,evidence_reference,reviewer_notes,created_by)
 values(p_requirement_id,p_jurisdiction_code,p_source_kind,btrim(p_title),btrim(p_issuer),nullif(btrim(p_source_url),''),nullif(btrim(p_version_label),''),p_published_at,p_effective_from,p_effective_until,lower(p_sha256),nullif(btrim(p_evidence_reference),''),nullif(btrim(p_reviewer_notes),''),v_user)
 returning id into v_id;
 insert into public.krim_market_regulatory_source_events(source_id,actor_user_id,previous_status,new_status,rationale,evidence_reference)
 values(v_id,v_user,null,'pending','Source version registered; not yet verified.',nullif(btrim(p_evidence_reference),''));
 insert into public.krim_audit_events(actor_user_id,event_type,entity_type,entity_id,source,metadata,new_state)
 values(v_user,'market_readiness.source_registered','krim_market_regulatory_sources',v_id::text,'market_readiness_console',
 jsonb_build_object('requirement_id',p_requirement_id,'source_kind',p_source_kind,'issuer',p_issuer),
 jsonb_build_object('review_status','pending','title',p_title));
 return jsonb_build_object('success',true,'source_id',v_id,'review_status','pending');
end; $$;

create or replace function public.krim_admin_review_regulatory_source(
 p_source_id bigint,p_new_status text,p_rationale text,p_evidence_reference text default null
) returns jsonb language plpgsql security definer set search_path=''
as $$
declare v_user uuid:=auth.uid(); v_source public.krim_market_regulatory_sources%rowtype; v_old text;
begin
 if v_user is null then raise exception using errcode='28000',message='Authentication required'; end if;
 if coalesce(auth.jwt()->>'aal','aal1')<>'aal2' then raise exception using errcode='42501',message='AAL2 required'; end if;
 if not private.krim_has_permission(v_user,1::bigint,'admin.platform') then raise exception using errcode='42501',message='Platform administrator permission required'; end if;
 if p_new_status not in ('source_checked','legal_review_pending','legal_reviewed','rejected','retired') or length(btrim(coalesce(p_rationale,'')))<20 then
  raise exception using errcode='22023',message='Valid review status and rationale of at least 20 characters required'; end if;
 select * into v_source from public.krim_market_regulatory_sources where id=p_source_id for update;
 if not found then raise exception using errcode='P0002',message='Source version not found'; end if;
 v_old:=v_source.review_status;
 if p_new_status='source_checked' and (v_source.source_kind not in ('official_primary','official_secondary') or v_source.sha256 is null or v_source.source_url is null) then
  raise exception using errcode='22023',message='Source check requires official URL and recorded SHA-256 snapshot'; end if;
 if p_new_status='legal_review_pending' and v_old not in ('source_checked','legal_review_pending') then
  raise exception using errcode='22023',message='Verify the official source before legal review'; end if;
 if p_new_status='legal_reviewed' and (v_old not in ('legal_review_pending','source_checked') or v_source.source_kind not in ('qualified_legal_opinion','qualified_tax_opinion') or nullif(btrim(p_evidence_reference),'') is null) then
  raise exception using errcode='22023',message='Legal/tax reviewed status requires a qualified opinion source and evidence reference'; end if;
 update public.krim_market_regulatory_sources set review_status=p_new_status,reviewed_by=v_user,reviewed_at=now(),
 evidence_reference=coalesce(nullif(btrim(p_evidence_reference),''),evidence_reference),reviewer_notes=left(coalesce(reviewer_notes||E'\n','')||btrim(p_rationale),4000)
 where id=p_source_id;
 insert into public.krim_market_regulatory_source_events(source_id,actor_user_id,previous_status,new_status,rationale,evidence_reference)
 values(p_source_id,v_user,v_old,p_new_status,btrim(p_rationale),nullif(btrim(p_evidence_reference),''));
 insert into public.krim_audit_events(actor_user_id,event_type,entity_type,entity_id,source,metadata,previous_state,new_state)
 values(v_user,'market_readiness.source_reviewed','krim_market_regulatory_sources',p_source_id::text,'market_readiness_console',
 jsonb_build_object('rationale',btrim(p_rationale),'evidence_reference',p_evidence_reference),
 jsonb_build_object('review_status',v_old),jsonb_build_object('review_status',p_new_status,'reviewed_at',now()));
 return jsonb_build_object('success',true,'source_id',p_source_id,'previous_status',v_old,'review_status',p_new_status);
end; $$;

