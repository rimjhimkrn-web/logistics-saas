create table if not exists public.krim_customs_broker_licenses (
 id bigint generated by default as identity primary key,
 organization_id bigint not null references public.krim_organizations(id) on delete restrict,
 country_id bigint not null references public.krim_countries(id) on delete restrict,
 authority_name text not null,
 license_number text not null,
 license_type text not null,
 valid_from date, valid_until date,
 status text not null default 'pending_review' check(status in ('pending_review','approved','rejected','expired','suspended')),
 evidence_path text,evidence_mime_type text,evidence_file_size bigint,
 submitted_by uuid not null,submitted_at timestamptz not null default now(),
 reviewed_by uuid,reviewed_at timestamptz,review_note text,
 created_at timestamptz not null default now(),updated_at timestamptz not null default now(),
 unique(organization_id,country_id,license_number)
);
create index if not exists krim_customs_broker_licenses_org_country_status_idx on public.krim_customs_broker_licenses(organization_id,country_id,status,valid_until);
alter table public.krim_customs_broker_licenses enable row level security;
alter table public.krim_customs_broker_licenses force row level security;
revoke all on public.krim_customs_broker_licenses from public,anon,authenticated;
grant select on public.krim_customs_broker_licenses to authenticated;
create policy "Customs broker licenses scoped read" on public.krim_customs_broker_licenses for select to authenticated using (
 exists(select 1 from public.krim_organization_members m where m.organization_id=organization_id and m.user_id=(select auth.uid()) and m.status='active')
 or private.krim_has_permission((select auth.uid()),1,'admin.platform')
);
create table if not exists public.krim_customs_broker_license_events (
 id bigint generated by default as identity primary key,
 license_id bigint not null references public.krim_customs_broker_licenses(id) on delete restrict,
 organization_id bigint not null references public.krim_organizations(id) on delete restrict,
 event_type text not null check(event_type in ('submitted','approved','rejected','suspended','expired')),
 actor_user_id uuid not null,event_note text not null default '',created_at timestamptz not null default now()
);
create index if not exists krim_customs_broker_license_events_license_idx on public.krim_customs_broker_license_events(license_id,created_at desc);
alter table public.krim_customs_broker_license_events enable row level security;
alter table public.krim_customs_broker_license_events force row level security;
revoke all on public.krim_customs_broker_license_events from public,anon,authenticated;
grant select on public.krim_customs_broker_license_events to authenticated;
create policy "Customs broker license events scoped read" on public.krim_customs_broker_license_events for select to authenticated using (
 exists(select 1 from public.krim_customs_broker_licenses l join public.krim_organization_members m on m.organization_id=l.organization_id
 where l.id=license_id and m.user_id=(select auth.uid()) and m.status='active')
 or private.krim_has_permission((select auth.uid()),1,'admin.platform')
);
grant usage on sequence public.krim_customs_broker_licenses_id_seq to authenticated;
grant usage on sequence public.krim_customs_broker_license_events_id_seq to authenticated;

create or replace function private.krim_customs_broker_license_submit(
 p_organization_id bigint,p_country_id bigint,p_authority_name text,p_license_number text,p_license_type text,
 p_valid_from date,p_valid_until date,p_evidence_path text,p_evidence_mime text,p_evidence_size bigint
) returns bigint language plpgsql security definer set search_path=public,storage,pg_catalog as $$
declare v_user uuid:=auth.uid(); v_license_id bigint;
begin
 if v_user is null then raise exception 'Authentication required'; end if;
 if p_valid_until is not null and p_valid_from is not null and p_valid_until<p_valid_from then raise exception 'Invalid license validity dates'; end if;
 if p_evidence_size is null or p_evidence_size<1 or p_evidence_size>10485760 then raise exception 'Evidence must be between 1 byte and 10 MB'; end if;
 if p_evidence_mime not in ('application/pdf','image/jpeg','image/png') then raise exception 'Unsupported evidence file type'; end if;
 if not exists(select 1 from public.krim_organizations o join public.krim_organization_members m on m.organization_id=o.id
 where o.id=p_organization_id and o.status='active' and o.organization_type='customs' and m.user_id=v_user and m.status='active'
 and private.krim_has_permission(v_user,p_organization_id,'compliance.view')) then raise exception 'Active customs membership and compliance permission required'; end if;
 if not exists(select 1 from public.krim_countries c where c.id=p_country_id and c.is_active) then raise exception 'Active jurisdiction required'; end if;
 if p_evidence_path not like 'customs/'||p_organization_id::text||'/'||v_user::text||'/%' then raise exception 'Invalid evidence storage path'; end if;
 if not exists(select 1 from storage.objects where bucket_id='krim-partner-verification' and name=p_evidence_path and owner=v_user
 and metadata->>'mimetype'=p_evidence_mime and (metadata->>'size')::bigint=p_evidence_size) then
 raise exception 'Evidence upload not found or does not match submitted details'; end if;
 insert into public.krim_customs_broker_licenses(organization_id,country_id,authority_name,license_number,license_type,valid_from,valid_until,evidence_path,evidence_mime_type,evidence_file_size,submitted_by)
 values(p_organization_id,p_country_id,left(trim(p_authority_name),200),left(trim(p_license_number),100),left(trim(p_license_type),100),p_valid_from,p_valid_until,p_evidence_path,p_evidence_mime,p_evidence_size,v_user)
 returning id into v_license_id;
 insert into public.krim_customs_broker_license_events(license_id,organization_id,event_type,actor_user_id,event_note)
 values(v_license_id,p_organization_id,'submitted',v_user,'Licence evidence submitted for independent review.');
 return v_license_id;
end; $$;

create or replace function private.krim_customs_broker_license_review(p_license_id bigint,p_decision text,p_note text)
returns boolean language plpgsql security definer set search_path=public,pg_catalog as $$
declare v_user uuid:=auth.uid(); v_org bigint; v_until date; v_status text;
begin
 if v_user is null then raise exception 'Authentication required'; end if;
 if coalesce(auth.jwt()->>'aal','aal1')<>'aal2' then raise exception 'Multi-factor authentication required'; end if;
 if not private.krim_has_permission(v_user,1,'admin.platform') then raise exception 'Platform admin permission required'; end if;
 select organization_id,valid_until,status into v_org,v_until,v_status from public.krim_customs_broker_licenses where id=p_license_id for update;
 if v_org is null then raise exception 'License record not found'; end if;
 if v_status<>'pending_review' then raise exception 'License is not awaiting review'; end if;
 if p_decision not in ('approved','rejected') then raise exception 'Invalid review decision'; end if;
 if p_decision='approved' and v_until is not null and v_until<current_date then raise exception 'Expired license cannot be approved'; end if;
 update public.krim_customs_broker_licenses set status=p_decision,reviewed_by=v_user,reviewed_at=now(),review_note=left(coalesce(p_note,''),2000),updated_at=now() where id=p_license_id;
 insert into public.krim_customs_broker_license_events(license_id,organization_id,event_type,actor_user_id,event_note)
 values(p_license_id,v_org,p_decision,v_user,left(coalesce(p_note,''),2000));
 return true;
end; $$;

