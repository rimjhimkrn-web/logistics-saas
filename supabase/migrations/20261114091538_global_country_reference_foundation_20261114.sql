returns jsonb language plpgsql security definer set search_path=''
as $$
declare v_user uuid:=auth.uid();
begin
 if v_user is null or coalesce(auth.jwt()->>'aal','')<>'aal2' or not private.krim_has_permission(v_user,1::bigint,'admin.platform') then
  raise exception using errcode='42501',message='AAL2 platform administrator access required';
 end if;
 return jsonb_build_object(
  'as_of',now(),'countries',(select count(*) from public.krim_countries),
  'countries_with_iso3',(select count(*) from public.krim_countries where iso3_code is not null and btrim(iso3_code)<>''),
  'countries_with_numeric_code',(select count(*) from public.krim_countries where iso_numeric_code is not null),
