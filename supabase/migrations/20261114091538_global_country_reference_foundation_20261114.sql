
-- KRIM global country reference metadata. Data sources and revisions are retained.
alter table public.krim_countries
 add column if not exists iso_numeric_code varchar(3),
 add column if not exists m49_region_code varchar(3),
 add column if not exists m49_subregion_code varchar(3),
 add column if not exists region_name text,
 add column if not exists subregion_name text,
 add column if not exists capital_city text,
 add column if not exists official_languages text[] not null default '{}',
 add column if not exists internet_domain text,
 add column if not exists reference_source text,
 add column if not exists reference_updated_at date;
alter table public.krim_currencies add column if not exists reference_source text, add column if not exists reference_updated_at date;
create table if not exists public.krim_country_currency_references(
 country_id bigint not null references public.krim_countries(id) on delete restrict,
 currency_code varchar(3) not null references public.krim_currencies(code) on delete restrict,
 reference_kind text not null default 'dataset_country_reference' check(reference_kind='dataset_country_reference'),
 source_dataset text not null, source_reference text not null, source_updated_at date not null,
 created_at timestamptz not null default now(), primary key(country_id,currency_code)
);
create table if not exists public.krim_country_time_zones(
 country_id bigint not null references public.krim_countries(id) on delete restrict,
 timezone_name text not null, timezone_note text,
 is_default_for_country boolean not null default false,
 source_dataset text not null, source_reference text not null, source_revision text not null,
 created_at timestamptz not null default now(), primary key(country_id,timezone_name)
);
create index if not exists krim_country_currency_refs_code_idx on public.krim_country_currency_references(currency_code);
create index if not exists krim_country_time_zones_name_idx on public.krim_country_time_zones(timezone_name);
create index if not exists krim_country_time_zones_default_idx on public.krim_country_time_zones(country_id) where is_default_for_country;
