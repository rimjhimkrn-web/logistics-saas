  'corridors_active',(select count(*) from public.krim_network_corridors where status='active'),
  'verified_active_partner_capabilities',(select count(*) from public.krim_partner_capabilities pc join public.krim_organizations o on o.id=pc.organization_id where pc.active=true and pc.verification_status='verified' and o.status='active'),
