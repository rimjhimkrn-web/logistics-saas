  'country_pack_controls_mandatory',(select count(*) from public.krim_country_pack_controls where mandatory),
  'country_pack_controls_approved',(select count(*) from public.krim_country_pack_controls where mandatory and review_status='approved' and applicability in ('yes','no','conditional') and source_id is not null and nullif(btrim(evidence_reference),'') is not null and nullif(btrim(reviewer_note),'') is not null and (expires_at is null or expires_at>now())),
