CREATE TABLE public.krim_security_permissions (
 id bigint generated by default as identity primary key,
 permission_code text not null unique,
 permission_name text not null,
 resource_type text not null,
 action text not null,
 description text,
 is_system_permission boolean not null default true,
 created_at timestamptz not null default now()
);
CREATE TABLE public.krim_role_permissions (
 id bigint generated by default as identity primary key,
 role_id bigint not null references public.krim_security_roles(id),
 permission_id bigint not null references public.krim_security_permissions(id),
 granted boolean not null default true,
 created_at timestamptz not null default now(),
 CONSTRAINT krim_role_permissions_unique UNIQUE(role_id,permission_id)
);
